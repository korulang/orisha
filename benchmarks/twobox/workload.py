#!/usr/bin/env python3
"""
A workload with the shape real web traffic has, split so we cannot cheat.

Two decisions here decide the answer before anything runs, so both are stated
rather than buried:

**The distribution.** Requests to a website are heavily skewed — a few pages take
most of the traffic and a long tail takes the rest. Sampling URLs uniformly at
random is the one shape where compile-time layout cannot possibly help, and it
is also a shape no real site has. Zipf is the standard model for this and it is
what we use; the exponent is a knob and it is printed, because at s=0 this
becomes uniform and the experiment is rigged to fail, while at s=3 almost every
request is one page and it is rigged to succeed.

**The split.** The profile the compiler sees and the traffic the benchmark sends
are drawn from the same distribution but are DIFFERENT SAMPLES. Compiling against
the exact sequence we then replay would measure memorisation and report it as a
speedup. Same shape, different draw — the compiler learns which pages are hot, it
never learns the request list.

  workload.py <site-dir> --train train.log --test test.lua [--zipf 1.1] [--seed 7]
"""
import argparse, os, random, sys
from urllib.parse import quote

ap = argparse.ArgumentParser()
ap.add_argument("site")
ap.add_argument("--train", required=True, help="access log the COMPILER reads")
ap.add_argument("--test", required=True, help="wrk lua script the LOAD sends")
ap.add_argument("--zipf", type=float, default=1.1)
ap.add_argument("--seed", type=int, default=7)
ap.add_argument("--train-n", type=int, default=50_000)
ap.add_argument("--test-n", type=int, default=20_000)
a = ap.parse_args()

paths = []
for root, _, files in os.walk(a.site):
    for f in files:
        if f.endswith(".gz"):
            continue
        rel = os.path.relpath(os.path.join(root, f), a.site).replace(os.sep, "/")
        paths.append("/" + rel)
paths.sort()
if not paths:
    sys.exit("no files found")

# Rank the pages once, then draw from that ranking twice. The ranking is the
# "truth" about which pages are popular; both samples inherit it.
rnd = random.Random(a.seed)
rnd.shuffle(paths)                      # popularity is not alphabetical
weights = [1.0 / ((i + 1) ** a.zipf) for i in range(len(paths))]

def draw(n, seed):
    r = random.Random(seed)
    return r.choices(paths, weights=weights, k=n)

train = draw(a.train_n, a.seed + 1)
test = draw(a.test_n, a.seed + 2)       # same shape, independent draw

with open(a.train, "w") as fh:
    for p in train:
        fh.write(f'127.0.0.1 - - [01/Jan/2026:00:00:00 +0000] "GET {p} HTTP/1.1" 200 0 "-" "-"\n')

with open(a.test, "w") as fh:
    fh.write("-- Generated by workload.py. Held out from the profile the compiler saw.\nlocal urls = {\n")
    for p in test:
        fh.write(f'  "{quote(p)}",\n')
    fh.write("""}
local i = 0
request = function()
  i = i + 1
  if i > #urls then i = 1 end
  return wrk.format("GET", urls[i], {["Accept-Encoding"]="gzip"})
end
""")

overlap = len(set(train[:1000]) & set(test[:1000]))
top = sorted({p: train.count(p) for p in set(train[:2000])}.items(), key=lambda kv: -kv[1])[:3]
print(f"routes={len(paths)} zipf={a.zipf} train={len(train)} test={len(test)}")
print(f"top of the profile: {', '.join(f'{p} x{c}' for p, c in top)}")
print(f"distinct in train={len(set(train))} distinct in test={len(set(test))}")
print(f"(the two samples share a distribution, not a sequence)")
